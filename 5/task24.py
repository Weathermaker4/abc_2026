#Описание шифра.
#В криптографии шифр Цезаря, также известный шифр сдвига, код Цезаря или сдвиг Цезаря,
#является одним из самых простых и широко известных методов шифрования.
#Это тип подстановочного шифра, в котором каждая буква в открытом тексте заменяется буквой на некоторое
#фиксированное количество позиций вниз по алфавиту. Например, со сдвигом влево 3, D будет заменен на A,
#E станет Б, и так далее. Метод назван в честь Юлия Цезаря, который использовал его в своей частной переписке.

#Задача.
#Считайте файл message.txt и зашифруйте  текст шифром Цезаря, при этом символы первой строки файла должны
#циклически сдвигаться влево на 1, второй строки — на 2, третьей строки — на три и т.д.
#В этой задаче удобно считывать файл построчно, шифруя каждую строку в отдельности.
#В каждой строчке содержатся различные символы. Шифровать нужно только буквы кириллицы.


import os

# Алфавит
RU_LOWER = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
RU_UPPER = "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"

# Текст для создания файла, если его нет
sample_text = """Драсьте, Артем!
Этот шифр не снился даже Дэну Брауну.
А может и снился, кто его знает..."""

# Проверяем наличие файла message.txt. Если нет - создаем
if not os.path.exists("message.txt"):
    with open("message.txt", "w", encoding="utf-8") as file:
        file.write(sample_text)
    print("Файл message.txt не найден. Теперь он создан!")

# Лямбда-функция для сдвига одной буквы влево
shift_char = lambda char, shift: (
    RU_LOWER[(RU_LOWER.index(char) - shift) % len(RU_LOWER)] if char in RU_LOWER else
    RU_UPPER[(RU_UPPER.index(char) - shift) % len(RU_UPPER)] if char in RU_UPPER else
    char  # Знаки препинания, пробелы и цифры не трогаем
)

# Читаем созданный или существующий файл построчно
with open("message.txt", "r", encoding="utf-8") as file:
    lines = file.readlines()

# Обрабатываем каждую строку с её номером (сдвигом)
encrypted_lines = [
    "".join(shift_char(char, line_num) for char in line)
    for line_num, line in enumerate(lines, start=1)
]

# Записываем результат в новый файл
with open("encrypted_message.txt", "w", encoding="utf-8") as file:
    file.writelines(encrypted_lines)

print("Проверь файл encrypted_message.txt!")
