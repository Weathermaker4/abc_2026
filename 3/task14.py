# todo: Дан массив размера N. Найти минимальное растояние между одинаковыми значениями в массиве и вывести их индексы.
# Одинаковых значение может быть два и более !
# Пример:
# mass = [1,2,17,54,30,89,2,1,6,2]


# Для числа 1 минимальное растояние в массиве по индексам: 0 и 7
# Для числа 2 минимальное растояние в массиве по индексам: 6 и 9
# Для числа 17 нет минимального растояния т.к элемент в массиве один.


mass = [1, 2, 17, 54, 30, 89, 2, 1, 6, 2]

# Находим все уникальные числа в массиве, не считая их два раза

unique_numbers = []
for num in mass:
    if num not in unique_numbers:
        unique_numbers.append(num)

# Смотрим каждое уникальное число
for num in unique_numbers:
    
    # Берем все индексы, где встречается текущее число
    indices = []
    for i in range(len(mass)):
        if mass[i] == num:
            indices.append(i)
            
    # Смотрим, сколько раз нашлось число
    if len(indices) < 2:
        print("Для числа", num, "нет min расстояния, значение в массиве одно")
    else:
        # Ищем минимальную разницу между индексами
        min_dist = 999999
        idx1 = 0
        idx2 = 0
        
        # Сравниваем индексы между собой
        for k in range(len(indices) - 1):
            dist = indices[k + 1] - indices[k]
            if dist < min_dist:
                min_dist = dist
                idx1 = indices[k]
                idx2 = indices[k + 1]
                
        print("Для числа", num, "минимальное расстояние в массиве по индексам:", idx1, "и", idx2)
